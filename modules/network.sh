#!/bin/bash

echo "=================================Network Monitoring==========================================="

HOSTNAME=$(hostname)
IP_ADDRESS=$(hostname -I | awk '{print $1}')

echo "Hostname	: $HOSTNAME"
echo "IP Address	: $IP_ADDRESS"

echo ""
echo "Network Interfaces"
echo "----------------------------------------------------------------------------------------------"

ip -br addr

echo "----------------------------------------------------------------------------------------------"

echo ""
echo "Network Statistics"
echo "----------------------------------------------------------------------------------------------"

awk 'NR > 2 {
	gsub(":", "", $1)
	printf "%-10s RX: %-12s TX: %-12s\n", $1, $2, $10
}' /proc/net/dev

echo "----------------------------------------------------------------------------------------------"

echo ""
echo "Active Connections : $(ss -tunH | wc -l)"

echo "=============================================================================================="
